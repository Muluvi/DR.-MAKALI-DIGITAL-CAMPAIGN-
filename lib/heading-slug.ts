// Turns a markdown heading into a stable, predictable id.
//
// Headings used to carry their section number ("4.3 SMS, USSD and the offline majority") and the
// id was the number with its dots swapped for dashes ("4-3"). Numbering is a print-document
// convention and it is gone: a heading is now its name, and the id is that name slugified
// ("sms-ussd-and-the-offline-majority").
//
// Two consequences worth knowing. First, an id now survives a section moving, which the numeric
// scheme never did — the 2026 renumbering is what produced most of the legacy table below.
// Second, two headings can share a name where the old numbers kept them apart, so a heading
// deeper than h2 whose name collides within its own file is qualified with its parent's slug.
// scripts/verify-deep-links.mjs asserts the result is unique.
const LEADING_NUMBER = /^(\d+(?:\.\d+)*)\.?\s/;

/** The section number a heading used to print, for resolving links minted before names. */
export function headingNumber(text: string): string | null {
  const match = LEADING_NUMBER.exec(text.trim());
  if (!match) return null;
  return match[1];
}

/** Slug from the heading's own words. A leading number, if one survives anywhere, is dropped. */
export function headingSlug(text: string): string | null {
  const withoutNumber = text.trim().replace(LEADING_NUMBER, "").trim();
  if (!withoutNumber) return null;
  const slug = withoutNumber
    .toLowerCase()
    .replace(/[\u2018\u2019\u201c\u201d]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 56)
    .replace(/-+$/g, "");
  return slug || null;
}

