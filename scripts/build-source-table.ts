#!/usr/bin/env node
/**
 * Annex A.2, the source table, generated from lib/data/figures.ts and never typed.
 *
 * Writes three tables between the source-table markers in content/annex-evidence.md:
 *   1. every sourced figure, grouped by the document it was read from, with that document's tier
 *      and the as-of dates its figures carry
 *   2. every modelled figure, with the note that says how it was computed
 *   3. every target, with the note that says whose it is
 * Needed figures are not repeated: they are the open items listed in Section 7.3.
 *
 * Values are written as {{tokens}}, so scripts/build-content.ts prints them from the same store.
 *   --check fails if the region on disk is stale.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FIGURES } from "../lib/data/figures.ts";
import type { Figure } from "../lib/data/schema.ts";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const FILE = path.join(ROOT, "content", "annex-evidence.md");
const START = "<!-- source-table:start (generated by scripts/build-source-table.ts; do not edit) -->";
const END = "<!-- source-table:end -->";
const CHECK = process.argv.includes("--check");

const TIER = { T1: "Tier 1", T2: "Tier 2", T3: "Tier 3" } as const;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const value = (f: Figure) => (f.unit === "percent" ? `{{${f.id}}}%` : f.unit === "ksh" ? `KSh {{${f.id}}}` : `{{${f.id}}}`);

const all = Object.values(FIGURES);
const sourced = all.filter((f) => f.state === "sourced");
const modelled = all.filter((f) => f.state === "modelled");
const targets = all.filter((f) => f.state === "target");
const needed = all.filter((f) => f.state === "needed");

const bySource = new Map<string, Figure[]>();
for (const f of sourced) {
  const key = `${f.source}\u0000${f.tier}`;
  bySource.set(key, [...(bySource.get(key) ?? []), f]);
}
const groups = [...bySource.entries()].sort(([a], [b]) => {
  const [sa, ta] = a.split("\u0000");
  const [sb, tb] = b.split("\u0000");
  return ta === tb ? sa.localeCompare(sb) : ta.localeCompare(tb);
});

const lines: string[] = [START, ""];
lines.push(
  `Every figure in the store, ${all.length} in all: ${sourced.length} read off a named document, ${modelled.length} modelled, ${targets.length} targets and ${needed.length} still needed. The needed figures are the open items listed in Section 7.3 and are not repeated here.`,
  "",
  "#### Sourced figures, by document",
  "",
  "<!-- keep -->",
  "| Document | Tier | As of | Figures read off it |",
  "|---|---|---|---|",
);
for (const [key, figs] of groups) {
  const [source, tier] = key.split("\u0000");
  const dates = [...new Set(figs.map((f) => f.asOf).filter(Boolean))].sort().join(", ") || "Not stated";
  const list = figs.map((f) => `\`${f.id}\` ${value(f)}`).join("; ");
  lines.push(`| ${cell(source)} | ${TIER[tier as keyof typeof TIER]} | ${dates} | ${list} |`);
}
lines.push("", "#### Modelled figures, and how each is computed", "", "<!-- keep -->", "| Figure | Value | Tier of its inputs | How it is computed |", "|---|---|---|---|");
for (const f of modelled) lines.push(`| \`${f.id}\` | ${value(f)} | ${f.tier ? TIER[f.tier] : "None"} | ${cell(f.note ?? "")} |`);
lines.push("", "#### Targets, and whose each is", "", "<!-- keep -->", "| Target | Value | Whose, and what it commits to |", "|---|---|---|");
for (const f of targets) lines.push(`| \`${f.id}\` | ${value(f)} | ${cell(f.note ?? "")} |`);
lines.push("", END);
const region = lines.join("\n");

const text = fs.readFileSync(FILE, "utf8");
const i = text.indexOf(START);
const j = text.indexOf(END);
if (i < 0 || j < 0) throw new Error("build-source-table: markers missing from content/annex-evidence.md");
const next = text.slice(0, i) + region + text.slice(j + END.length);

if (CHECK) {
  if (next !== text) {
    console.error("build-source-table: Annex A.2 is stale; run npm run content");
    process.exit(1);
  }
  console.log(`build-source-table: Annex A.2 lists ${all.length} figures from ${groups.length} documents, current`);
} else {
  fs.writeFileSync(FILE, next);
  console.log(`build-source-table: Annex A.2 lists ${all.length} figures from ${groups.length} documents`);
}
