#!/usr/bin/env node
/**
 * The November 2026 restructure's preservation guard (nothing deleted).
 *
 * The restructure renumbered every section, so the section-keyed word balance in
 * scripts/declutter/check-content.mjs cannot compare across it. This check takes its place for the
 * move: for every unit of the Step 0 inventory that carries a {{figure}} token, an acronym or a
 * proper name, each of them must still be present in the file where the approved plan put that
 * unit (or, for a merge, in the file of the passage it merged into). The list it reads,
 * docs/restructure-2026-11/preservation.json, is generated by build-preservation.py.
 *
 *     node scripts/restructure-2026-11/check-preservation.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isRetiredFile, isRetiredText } from "../rivals-2026-11/retired.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const { units } = JSON.parse(fs.readFileSync(path.join(ROOT, "docs", "restructure-2026-11", "preservation.json"), "utf8"));
const cache = new Map();
const read = (f) => {
  // Annex A.2 is generated from the whole figures store, so it would vouch for any token: it is
  // left out, and a unit placed in Annex A must hold its facts in the prose.
  if (!cache.has(f)) {
    const t = fs.existsSync(path.join(ROOT, f)) ? fs.readFileSync(path.join(ROOT, f), "utf8") : "";
    cache.set(f, t.replace(/<!-- source-table:start[\s\S]*?<!-- source-table:end -->/, ""));
  }
  return cache.get(f);
};
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// Disputes settled on 1 November 2026 (docs/disputes-resolved.json). "CONFLICT" is the word in the
// `[CONFLICT Cn: see open items]` markers, which are markup, and check-content.mjs check 9 already
// requires every unsettled marker to stay put; a token is excused only in the file the decision
// names, so nothing else can slip through.
const settledFile = path.join(ROOT, "docs", "disputes-resolved.json");
const settlement = fs.existsSync(settledFile) ? JSON.parse(fs.readFileSync(settledFile, "utf8")) : { settled: [], retiredTokens: [] };
const markersSettled = settlement.settled.length > 0;
const retired = new Set((settlement.retiredTokens ?? []).map((r) => `${r.file}|${r.token}`));

// The consolidation pass (docs/consolidation-2026-11/ledger.json) moves passages between files. A
// unit is also looked for in every file its file's passages were moved to, by a logged move, so a
// merged section keeps its preservation check where it now lives, and nowhere else.
const consolidationLedger = path.join(ROOT, "docs", "consolidation-2026-11", "ledger.json");
// A logged duplicate (two copies of a fact met, one became a pointer) names the home where the
// facts stay, and is followed the same way, after the moves, so a passage moved and then deduped is
// looked for where its facts now live.
const movedTo = new Map();
const dupTo = new Map();
for (const c of fs.existsSync(consolidationLedger) ? JSON.parse(fs.readFileSync(consolidationLedger, "utf8")) : []) {
  const target = c.kind === "moved" ? c.to : c.kind === "duplicate" ? c.home : null;
  if (!target) continue;
  const from = `content/${c.file}.md`;
  const to = `content/${target.split(":")[0]}.md`;
  if (from === to) continue;
  const map = c.kind === "moved" ? movedTo : dupTo;
  map.set(from, new Set([...(map.get(from) ?? []), to]));
}
const withMoves = (files) => {
  // Moves are followed to the end of the chain: a passage the consolidation pass moved, and a later
  // pass (the table-of-contents restructure, docs/toc-2026-11) moved again, is looked for where it
  // now lives, and in every file along the way.
  const moved = new Set(files);
  for (let grew = true; grew; ) {
    grew = false;
    for (const f of [...moved]) for (const t of movedTo.get(f) ?? []) if (!moved.has(t)) { moved.add(t); grew = true; }
  }
  return [...new Set([...moved].flatMap((f) => [f, ...(dupTo.get(f) ?? [])]))];
};

const RIVALS_FILES = new Set(
  (fs.existsSync(path.join(ROOT, "docs", "rivals-2026-11", "ledger.json")) ? JSON.parse(fs.readFileSync(path.join(ROOT, "docs", "rivals-2026-11", "ledger.json"), "utf8")) : []).map((e) => `content/${e.file}.md`),
);
const errors = [];
let checked = 0;
for (const u of units) {
  const text = withMoves(u.files).map(read).join("\n");
  const excused = (t) => u.files.some((f) => retired.has(`${f}|{{${t}}}`));
  // The rivals pass (docs/rivals-2026-11) removed whole chapters and passages by Firefly's decision.
  // An item is excused only where the unit lives in a file that pass removed or changed, and the
  // item itself is in the text the pass logged as removed.
  const rivalsTouched = withMoves(u.files).some((f) => isRetiredFile(f) || RIVALS_FILES.has(f));
  const retiredItem = (n) => rivalsTouched && isRetiredText(n);
  const missing = [
    ...u.tokens.filter((t) => !excused(t) && !new RegExp(`\\{\\{${esc(t)}(\\|[a-z0-9]+)?\\}\\}`).test(text) && !retiredItem(`{{${t}`)).map((t) => `{{${t}}}`),
    ...[...u.acronyms, ...u.names]
      .filter((n) => !(markersSettled && n === "CONFLICT"))
      .filter((n) => !new RegExp(`(?<![\\w])${esc(n)}(?![\\w])`).test(text) && !retiredItem(n)),
  ];
  checked += u.tokens.length + u.acronyms.length + u.names.length;
  if (missing.length) errors.push(`${u.c} (${u.from}, ${u.treatment}) → ${u.files.join(", ")}: missing ${missing.join(", ")}`);
}

if (errors.length) {
  console.error(`check-preservation: ${errors.length} unit(s) lost a token, acronym or name`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
console.log(`check-preservation: ${units.length} units, ${checked} tokens, acronyms and names, all still at their new location`);
