#!/usr/bin/env python3
"""Old heading id -> the heading that holds its text after the November 2026 restructure.

Every id live before the restructure (docs/restructure-2026-11/units.json) is mapped to where its
heading's text went in the approved plan: the section its heading unit moved to, or, for a heading
merged into another, the section the surviving passage moved to. A target that is not a live heading
climbs to its parent; a chapter-level target lands on the chapter's first heading. Writes
lib/anchors/restructure-2026-11.json, which scripts/build-anchors.ts reads first.

    python3 scripts/restructure-2026-11/build-moves.py .
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
DOCS = ROOT / "docs" / "restructure-2026-11"
units = json.loads((DOCS / "units.json").read_text())
plan = json.loads((DOCS / "plan.json").read_text())["plan"]
sys.path.insert(0, str(Path(__file__).parent))

# The old -> new number map is the one the citations use, so a link and a citation agree.
import subprocess  # noqa: E402

NUM = {}
for line in subprocess.run([sys.executable, "-I", str(Path(__file__).parent / "renumber.py"), str(ROOT), "map"],
                           capture_output=True, text=True, check=True).stdout.splitlines():
    old, new = [x.strip() for x in line.split("->")]
    NUM[old] = new

LEADING = re.compile(r"^((?:\d+[A-Z]?(?:\.\d+)*|[A-H](?:\.\d+)+))\.?\s")
HEADING = re.compile(r"^(#{2,3})\s+(.+?)\s*$")
live, by_route = set(), {}
for f in sorted((ROOT / "public" / "content").glob("*.md")):
    route, ids, fence = f.stem, [], False
    for line in f.read_text().split("\n"):
        if line.strip().startswith("```"):
            fence = not fence
            continue
        m = None if fence else HEADING.match(line)
        if not m:
            continue
        t = m.group(2).replace("**", "").replace("*", "").replace("`", "").strip()
        n = LEADING.match(t)
        if n:
            ids.append(f"{route}-sec-" + n.group(1).replace(".", "-").lower())
    by_route[route] = ids
    live.update(ids)

CHAPTER_ROUTE = {
    "1": "kitui", "2": "votes", "3": "needs", "4": "news", "5": "race", "6": "record", "7": "diagnosis",
    "8": "goal", "9": "position", "10": "message", "11": "voters", "12": "channels", "13": "engagement",
    "14": "timeline", "16": "coalitions", "17": "team", "18": "success", "19": "lawful", "20": "response",
    "21": "receives", "22": "commitments", "23": "ask",
}
WS_ROUTE = {"1": "workstreams-platforms", "2": "workstreams-media", "3": "workstreams-ground", "4": "workstreams-data"}
ANNEX_ROUTE = {"A": "annex-evidence", "B": "annex-county", "C": "annex-playbooks", "D": "annex-volunteers",
               "E": "annex-technology", "F": "annex-runbooks", "G": "annex-terms", "H": "annex-glossary"}


def target_id(num):
    parts = num.split(".")
    route = WS_ROUTE[parts[1] if len(parts) > 1 else "1"] if parts[0] == "15" else CHAPTER_ROUTE.get(parts[0]) or ANNEX_ROUTE[parts[0]]
    while parts:
        cand = f"{route}-sec-" + "-".join(parts).lower()
        if cand in live:
            return cand
        parts = parts[:-1]
    return by_route[route][0]


moves = {}
for u in units:
    if u.get("hid"):
        moves[u["hid"]] = target_id(NUM[u["section"]])

bad = [f"{k} -> {v}" for k, v in moves.items() if v not in live]
if bad:
    sys.exit("build-moves: targets not live: " + ", ".join(bad))
out = {
    "$comment": "GENERATED by scripts/restructure-2026-11/build-moves.py. Old deep-link id -> the heading that holds its text after the November 2026 restructure.",
    "moves": dict(sorted(moves.items())),
}
(ROOT / "lib" / "anchors" / "restructure-2026-11.json").write_text(json.dumps(out, indent=1) + "\n")
print(f"build-moves: {len(moves)} ids mapped onto {len(set(moves.values()))} live headings ({len(live)} live)")
