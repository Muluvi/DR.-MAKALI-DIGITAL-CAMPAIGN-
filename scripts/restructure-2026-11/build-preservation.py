#!/usr/bin/env python3
"""Write docs/restructure-2026-11/preservation.json: what each inventory unit must still carry.

For every unit in the Step 0 inventory (units.json, local only), the facts that cannot be reworded
away: every {{figure}} token, every acronym of three or more capitals, and every proper name from
the list below. Each unit also names the file or files where the approved plan put it: its own
new location, plus, for a merge, the location of the passage it merged into. The committed JSON is
what scripts/restructure-2026-11/check-preservation.mjs reads, so the guard needs no local file.

    python3 scripts/restructure-2026-11/build-preservation.py .
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
DOCS = ROOT / "docs" / "restructure-2026-11"
units = json.loads((DOCS / "units.json").read_text())
plan = json.loads((DOCS / "plan.json").read_text())["plan"]
register = json.loads((ROOT / "data" / "ward-register.json").read_text())

NAMES = {"Kasalu", "Wambua", "Malombe", "Ngilu", "Musila", "Kalonzo", "Musyoka", "Mulu", "Makali",
         "Mwingi", "Mutomo", "Ikutha", "Mui", "Kitui", "Nairobi", "Wiper", "Safaricom", "Airtel",
         "Meta", "Facebook", "WhatsApp", "TikTok", "Instagram", "YouTube", "Kikamba", "Kiswahili"}
for c in register["constituencies"]:
    NAMES.add(c["name"])
    for w in c["wards"]:
        NAMES.add(w["name"])

# Shouted capitals in headings and callouts ("THE WINDOW", "LEVEL 1 — LEAN") are not acronyms, and
# a [CHECK REF] marker is meant to go when its unit is corrected.
SHOUTED = {"THE", "NOT", "AND", "FOR", "DEADLINE", "WINDOW", "LEAN", "STANDARD", "PREMIUM", "ANNEX",
           "CEILING", "CRITICAL", "DIGITAL", "REALITY", "STRATEGIC", "ACTION", "COMPLIANCE",
           "CONFIRMATION", "DIRECTIVE", "ITEM", "REQUIRED", "MUST", "CHARTER", "DATA", "OUR",
           "ETHICS", "HIGH", "RISK", "LOW", "MINIMAL", "MODERATE", "STOP", "SIMAMA", "ONDOKA", "CANCEL",
           "SFX", "VERIFY", "CONFIRM", "EDIT", "NEEDED", "WARNING"}
MARKERS = {"CHECK", "REF"}
# Tokens a correction removed on purpose, each with its reason.
DROPPED = {
    "C924": ("sub.kitui-west.density",),  # a population density printed as a share of segments; withdrawn
}

# Where each section number now lives: every file whose numbered heading carries it or a part of it
# (Chapter 15 spans four files).
HEAD = re.compile(r"^#{2,3} ((?:\d+|[A-H])(?:\.\d+)*)\s")
where = {}
for f in sorted((ROOT / "content").glob("*.md")):
    for line in f.read_text().splitlines():
        m = HEAD.match(line)
        if m:
            parts = m.group(1).split(".")
            for i in range(1, len(parts) + 1):
                where.setdefault(".".join(parts[:i]), set()).add(f"content/{f.name}")
where["Cover"] = {"content/cover.md"}
where["In"] = {"content/brief.md"}
where["Brief"] = {"content/brief.md"}
NUMREF = re.compile(r"(?<![\w.])(\d+(?:\.\d+)*|[A-H](?:\.\d+)+)(?![\w])")


def files_for(loc, note=""):
    key = loc.split(" ")[0]
    if key not in where:
        raise SystemExit(f"build-preservation: no file for location {loc!r}")
    out = set(where[key])
    # A split unit names each destination in its note ("water → 3.1; youth → 3.5").
    if note.startswith("Split"):
        for dest in re.findall(r"→\s*([^;.]+)", note):
            for n in NUMREF.findall(dest):
                out |= where.get(n, set())
    return out


TOKEN = re.compile(r"\{\{([a-z0-9.\-]+)(?:\|[a-z0-9]+)?\}\}")
ACRO = re.compile(r"\b[A-Z][A-Z0-9]{2,}\b")
out = []
for u in units:
    c = u["c"]
    p = plan[c]
    files = files_for(p["loc"], p.get("note", ""))
    m = re.match(r"Merged with (C\d+)", p["t"])
    if m:
        files |= files_for(plan[m.group(1)]["loc"], plan[m.group(1)].get("note", ""))
    text = u["raw"]
    tokens = sorted(set(TOKEN.findall(text)))
    acronyms = sorted(set(a for a in ACRO.findall(text) if a not in SHOUTED
                          and not (a in MARKERS and (p["t"] == "Corrected" or "[CHECK REF]" not in text))))
    tokens = [t for t in tokens if t not in DROPPED.get(c, ())]
    names = sorted(n for n in NAMES if re.search(r"(?<![\w])" + re.escape(n) + r"(?![\w])", text))
    if tokens or acronyms or names:
        out.append({"c": c, "from": f"{u['file']}:{u['line']}", "treatment": p["t"], "files": sorted(files),
                    "tokens": tokens, "acronyms": acronyms, "names": names})

(DOCS / "preservation.json").write_text(json.dumps({
    "$comment": "Generated by scripts/restructure-2026-11/build-preservation.py from the Step 0 inventory and the approved plan. Checked by check-preservation.mjs.",
    "units": out}, indent=1, ensure_ascii=False) + "\n")
print(f"build-preservation: {len(out)} of {len(units)} units carry tokens, acronyms or names")
