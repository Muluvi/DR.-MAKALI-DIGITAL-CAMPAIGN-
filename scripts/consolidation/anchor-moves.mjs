#!/usr/bin/env node
/**
 * Old heading id -> the heading that holds its text after the consolidation pass's section merges.
 *
 * Every heading id live at the pass's base (2f29920, read from public/content/*.md at that commit)
 * that is not live today is mapped here. Section numbers are unique across the whole document and a
 * merge moves a section with its number, so "votes-sec-b-1" lands on whichever route now carries
 * the heading numbered B.1. A heading whose number did not survive is named in
 * docs/consolidation-2026-11/anchor-overrides.json. An id that maps to nothing fails.
 *
 * Writes lib/anchors/consolidation-2026-11.json, which scripts/build-anchors.ts reads first.
 *
 *     node scripts/consolidation/anchor-moves.mjs           # write
 *     node scripts/consolidation/anchor-moves.mjs --check   # fail if it would change
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const BASE = "2f29920";
const OUT = path.join(ROOT, "lib", "anchors", "consolidation-2026-11.json");
const OVERRIDES = path.join(ROOT, "docs", "consolidation-2026-11", "anchor-overrides.json");

const LEADING = /^((?:\d+[A-Z]?(?:\.\d+)*|[A-H](?:\.\d+)+))\.?\s/;
const HEADING = /^(#{2,3})\s+(.+?)\s*$/;
const clean = (raw) => raw.replace(/\*\((new|updated)\)\*/gi, "").replace(/\*\*/g, "").replace(/\*/g, "").replace(/`/g, "").trim();

function idsOf(route, text) {
  const ids = [];
  let fence = false;
  for (const line of text.split("\n")) {
    if (/^\s*```/.test(line)) { fence = !fence; continue; }
    if (fence) continue;
    const m = HEADING.exec(line);
    if (!m) continue;
    const n = LEADING.exec(clean(m[2]));
    if (n) ids.push({ id: `${route}-sec-${n[1].replace(/\./g, "-").toLowerCase()}`, slug: n[1].replace(/\./g, "-").toLowerCase() });
  }
  return ids;
}

const baseFiles = execFileSync("git", ["ls-tree", "--name-only", BASE, "public/content/"], { cwd: ROOT, encoding: "utf8" })
  .split("\n").filter((f) => f.endsWith(".md"));
const before = baseFiles.flatMap((f) => idsOf(path.basename(f, ".md"), execFileSync("git", ["show", `${BASE}:${f}`], { cwd: ROOT, encoding: "utf8" })));

const nowDir = path.join(ROOT, "public", "content");
const now = fs.readdirSync(nowDir).filter((f) => f.endsWith(".md")).flatMap((f) => idsOf(path.basename(f, ".md"), fs.readFileSync(path.join(nowDir, f), "utf8")));
const live = new Set(now.map((x) => x.id));
const bySlug = new Map();
for (const x of now) bySlug.set(x.slug, [...(bySlug.get(x.slug) ?? []), x.id]);
const overrides = fs.existsSync(OVERRIDES) ? JSON.parse(fs.readFileSync(OVERRIDES, "utf8")).overrides : {};

const moves = {};
const lost = [];
for (const { id, slug } of before) {
  if (live.has(id)) continue;
  const target = overrides[id] ?? (bySlug.get(slug)?.length === 1 ? bySlug.get(slug)[0] : null);
  if (target && live.has(target)) moves[id] = target;
  else lost.push(id);
}
if (lost.length) {
  console.error(`anchor-moves: ${lost.length} heading(s) live at ${BASE} land on nothing; name them in ${path.relative(ROOT, OVERRIDES)}:`);
  for (const id of lost) console.error(`  - ${id}`);
  process.exit(1);
}

const body = JSON.stringify({
  $comment: "GENERATED by scripts/consolidation/anchor-moves.mjs. Old deep-link id (live at 2f29920) -> the heading that holds its text after the consolidation pass.",
  moves: Object.fromEntries(Object.entries(moves).sort()),
}, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== body) {
    console.error("anchor-moves: lib/anchors/consolidation-2026-11.json is stale. Run: node scripts/consolidation/anchor-moves.mjs");
    process.exit(1);
  }
  console.log(`anchor-moves: ${Object.keys(moves).length} moved headings, all landing on live headings`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`anchor-moves: wrote ${Object.keys(moves).length} moves`);
}
