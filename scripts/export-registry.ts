#!/usr/bin/env node
/**
 * The registry, exported for everything that is not the site: data/registry.export.json.
 *
 * lib/data/figures.ts is the one place a figure lives. The analysis model (analysis/) reads its site
 * figures from this export instead of retyping them (analysis/config/assumptions.yaml names a
 * registry id with `site_figure:`; analysis/src/config.py resolves it here), so a refresh of the
 * registry flows into the model on its next run (consolidation pass, Step 5).
 *
 * One record per figure: id, value, unit, tier, state, source, as-of date, and the note that says
 * how a modelled figure is computed or whose a target is.
 *
 *     node --experimental-strip-types scripts/export-registry.ts           # write
 *     node --experimental-strip-types scripts/export-registry.ts --check   # fail if stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FIGURES } from "../lib/data/figures.ts";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "data", "registry.export.json");

const figures = Object.values(FIGURES)
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((f) => ({
    id: f.id,
    value: f.value,
    unit: f.unit,
    tier: f.tier,
    state: f.state,
    source: f.source,
    asOf: f.asOf ?? null,
    note: f.note ?? null,
  }));

const body = JSON.stringify({
  $comment: "GENERATED by scripts/export-registry.ts from lib/data/figures.ts. Do not edit: change the registry and rebuild.",
  count: figures.length,
  figures,
}, null, 1) + "\n";

if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== body) {
    console.error("export-registry: data/registry.export.json is stale. Run: npm run content");
    process.exit(1);
  }
  console.log(`export-registry: ${figures.length} figures, current`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`export-registry: wrote ${figures.length} figures to data/registry.export.json`);
}
