#!/usr/bin/env node
/**
 * Where a deep link into a heading the rivals pass removed now lands.
 *
 * Every heading id live at the pass's base (d034eb1, public/content/*.md) that is not live today is
 * mapped to a live heading: the removed chapters land on the chapter that now holds their place in
 * the argument, and a section removed from inside a kept chapter lands on the section before it.
 * scripts/build-anchors.ts and scripts/consolidation/anchor-moves.mjs read the result, so a shared
 * link never lands on nothing.
 *
 *     node scripts/rivals-2026-11/anchors.mjs           # write lib/anchors/rivals-2026-11.json
 *     node scripts/rivals-2026-11/anchors.mjs --check   # fail if it would change
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RIVALS_BASE } from "./retired.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = path.join(ROOT, "lib", "anchors", "rivals-2026-11.json");
const LEADING = /^((?:\d+[A-Z]?(?:\.\d+)*|[A-H](?:\.\d+)+))\.?\s/;
const HEADING = /^(#{2,3})\s+(.+?)\s*$/;
const clean = (raw) => raw.replace(/\*\((new|updated)\)\*/gi, "").replace(/\*\*/g, "").replace(/\*/g, "").replace(/`/g, "").trim();

/** The removed chapters, and the live heading each one's links now open on. */
const CHAPTER_LANDING = {
  race: "record-sec-6-1", // The race for 2027 -> His record and reach
  response: "lawful-sec-19-1", // Risks and response -> Lawful and ethical
  "annex-runbooks": "annex-technology-sec-e-1", // Runbooks -> Technology
};

function idsOf(route, text) {
  const ids = [];
  let fence = false;
  for (const line of text.split("\n")) {
    if (/^\s*```/.test(line)) { fence = !fence; continue; }
    if (fence) continue;
    const m = HEADING.exec(line);
    if (!m) continue;
    const n = LEADING.exec(clean(m[2]));
    if (n) ids.push({ id: `${route}-sec-${n[1].replace(/\./g, "-").toLowerCase()}`, slug: n[1].replace(/\./g, "-").toLowerCase() });
  }
  return ids;
}

const git = (args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8" });
const base = git(["ls-tree", "--name-only", RIVALS_BASE, "public/content/"])
  .split("\n").filter((f) => f.endsWith(".md"))
  .map((f) => ({ route: path.basename(f, ".md"), ids: idsOf(path.basename(f, ".md"), git(["show", `${RIVALS_BASE}:${f}`])) }));
const nowDir = path.join(ROOT, "public", "content");
const live = new Set(fs.readdirSync(nowDir).filter((f) => f.endsWith(".md")).flatMap((f) => idsOf(path.basename(f, ".md"), fs.readFileSync(path.join(nowDir, f), "utf8")).map((x) => x.id)));

const moves = {};
const slugs = {};
const lost = [];
for (const { route, ids } of base) {
  let previous = null;
  for (const { id, slug } of ids) {
    if (live.has(id)) { previous = id; continue; }
    const target = CHAPTER_LANDING[route] ?? previous;
    if (!target || !live.has(target)) { lost.push(id); continue; }
    moves[id] = target;
    slugs[slug] = target;
  }
}
if (lost.length) {
  console.error(`rivals anchors: ${lost.length} removed heading(s) land on nothing: ${lost.join(", ")}`);
  process.exit(1);
}
const body = JSON.stringify({
  $comment: "GENERATED by scripts/rivals-2026-11/anchors.mjs. A heading id live at d034eb1 that the rivals pass removed -> the live heading its links now land on; `slugs` is the same map by section number, for older ids that reached those headings by number.",
  moves: Object.fromEntries(Object.entries(moves).sort()),
  slugs: Object.fromEntries(Object.entries(slugs).sort()),
}, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== body) {
    console.error("rivals anchors: lib/anchors/rivals-2026-11.json is stale. Run: node scripts/rivals-2026-11/anchors.mjs");
    process.exit(1);
  }
  console.log(`rivals anchors: ${Object.keys(moves).length} removed headings, all landing on live headings`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`rivals anchors: wrote ${Object.keys(moves).length} landings`);
}
