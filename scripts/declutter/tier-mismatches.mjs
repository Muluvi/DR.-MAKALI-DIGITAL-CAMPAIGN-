#!/usr/bin/env node
/**
 * X1 (brief 2026-10 declutter, 5.4): a token whose data tier disagrees with the tier typed beside it.
 *
 * For every `{{token}}` in content/*.md that a "(Tier N…)" parenthetical directly follows (within four words),
 * the token's tier in lib/data/figures.ts is compared with the typed one. A disagreement is not
 * resolved: the typed tier is what renders, and the pair is listed in docs/declutter/TIER-MISMATCHES.md.
 *
 *     node --no-warnings --experimental-strip-types scripts/declutter/tier-mismatches.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { FIGURES } from "../../lib/data/figures.ts";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const OUT = path.join(ROOT, "docs/declutter/TIER-MISMATCHES.md");
const files = fs.readdirSync(path.join(ROOT, "content")).filter((f) => f.endsWith(".md")).sort();

const rows = [];
let pairs = 0;
for (const f of files) {
  const lines = fs.readFileSync(path.join(ROOT, "content", f), "utf8").split("\n");
  let heading = "(intro)";
  lines.forEach((line, i) => {
    const h = /^#{2,3}\s+(\S+)\s/.exec(line);
    if (h) heading = h[1];
    // A sentence: up to the next full stop that is not inside a token or a number.
    for (const m of line.matchAll(/\{\{([a-z0-9.-]+)(?:\|[a-z0-9]+)?\}\}([^{}]*?)\((Tier ([123])[^)]*)\)/gi)) {
      // The parenthetical must sit right after the token (four words at most between them), or it may
      // grade another figure in the sentence: 2.6.1's "(Tier 2, a media report…)" follows the
      // governor's total but grades Kasalu's result before it.
      if (/[.!?]\s/.test(m[2]) || (m[2].match(/[A-Za-z]{2,}/g) ?? []).length > 4) continue;
      const fig = FIGURES[m[1]];
      if (!fig) continue;
      pairs += 1;
      const data = fig.tier ? fig.tier.replace("T", "") : fig.state;
      if (String(data) !== m[4]) rows.push({ file: f.replace(/\.md$/, ""), heading, line: i + 1, token: m[1], data: fig.tier ?? fig.state, typed: m[3] });
    }
  });
}

const md = [
  "# Tier mismatches",
  "",
  "X1 (brief 2026-10 declutter, 5.4): where a `{{token}}` is followed directly (within four words) by a typed \"(Tier N …)\" parenthetical, the token's tier in `lib/data/figures.ts` is compared with the typed one. **Nothing here is resolved.** The typed tier is what the badge shows, as the brief requires. Each row is for the owner to settle.",
  "",
  `Generated by \`scripts/declutter/tier-mismatches.mjs\`: ${pairs} token and parenthetical pairs checked, ${rows.length} disagree.`,
  "",
  ...(rows.length
    ? ["| File | Section | Line | Token | Tier in the data | Typed in the text |", "|---|---|---:|---|---|---|", ...rows.map((r) => `| ${r.file} | ${r.heading} | ${r.line} | \`${r.token}\` | ${r.data} | ${r.typed.replace(/\|/g, "\\|")} |`)]
    : ["No disagreements."]),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== md) { console.error("tier-mismatches: TIER-MISMATCHES.md is stale; run without --check"); process.exit(1); }
  console.log(`tier-mismatches: TIER-MISMATCHES.md is current (${rows.length} of ${pairs})`);
} else {
  fs.writeFileSync(OUT, md);
  console.log(`tier-mismatches: ${pairs} pairs checked, ${rows.length} disagree; wrote docs/declutter/TIER-MISMATCHES.md`);
}
