#!/usr/bin/env python3
"""Old deep-link id -> new deep-link id, for every id the site served before the restructure.

Two sets of old ids exist at the baseline commit (9681948):
  - the 205 live heading ids, "<file>-sec-<slug>", one per numbered heading in mapping.json;
  - the 1,369 keys of lib/anchors/redirects.ts, older ids that already redirected to one of those.

Each live id goes to the heading that now holds its text: the mapping row's newRef, located in the
new content (a run-in goes to its parent; a merge to its target; a removal to its canonical home).
Each redirect key goes wherever its old target now goes, so a link that worked yesterday lands on
the same text today. The result is written to lib/anchors/restructure-2026-10.json, which
scripts/build-anchors.ts reads ahead of every older move.

    python3 -I scripts/restructure-2026-10/build-moves.py
"""
import glob, json, os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MAPPING = json.load(open(os.path.join(ROOT, "docs", "restructure-2026-10", "mapping.json"), encoding="utf8"))
LEADING = re.compile(r"^((?:\d+[A-Z]?(?:\.\d+)*|[A-G](?:\.\d+)+))\.?\s")
HEADING = re.compile(r"^(#{2,3})\s+(.+?)\s*$")


def clean(raw):
    return re.sub(r"\*\((new|updated)\)\*", "", raw, flags=re.I).replace("**", "").replace("*", "").replace("`", "").strip()


def slug(num):
    return num.replace(".", "-").lower()


# Where every new number lives.
where = {}
for path in sorted(glob.glob(os.path.join(ROOT, "content", "*.md"))):
    route = os.path.basename(path)[:-3]
    fence = False
    for line in open(path, encoding="utf8"):
        if re.match(r"^\s*```", line):
            fence = not fence
            continue
        if fence:
            continue
        h = HEADING.match(line.rstrip("\n"))
        if not h:
            continue
        n = LEADING.match(clean(h.group(2)))
        if n:
            if n.group(1) in where:
                sys.exit(f"build-moves: number {n.group(1)} appears in both {where[n.group(1)]} and {route}")
            where[n.group(1)] = route
live_new = {f"{r}-sec-{slug(n)}" for n, r in where.items()}

# Targets that are not a plain number in the mapping, decided here and logged in CHANGELOG.md.
SPECIAL = {
    # F.2 merged into the cover, which carries no numbered heading. F.1 holds the pointer to the cover.
    "Cover": "annex-terms-sec-f-1",
    # 6.2 split: its own text (the ODPC action box) is 5.3.6; its subsection 6.2.1 has its own row.
    "5.3.6 / 1.8": "measurement-sec-5-3-6",
}

moves = {}
for r in MAPPING:
    if not r["oldRef"]:
        continue  # run-ins carry no id
    old = f"{r['file']}-sec-{slug(r['oldRef'])}"
    target = r["newRef"].replace(" (run-in)", "").strip()
    if target in SPECIAL:
        new = SPECIAL[target]
    else:
        if target not in where:
            sys.exit(f"build-moves: {r['oldRef']} -> {target}: no such heading in the new content")
        new = f"{where[target]}-sec-{slug(target)}"
    moves[old] = new

# The older redirect keys, composed through the same map.
src = subprocess.check_output(["git", "show", "9681948:lib/anchors/redirects.ts"], cwd=ROOT).decode()
old_redirects = json.loads(src[src.index("{"): src.rindex("}") + 1])
for key, target in old_redirects.items():
    if target not in moves:
        sys.exit(f"build-moves: old redirect {key} -> {target}: target was not a live heading at the baseline")
    moves.setdefault(key, moves[target])

# An old id that is also a new live id means two different headings: the new one wins at runtime
# (lib/heading-slug.ts checks live ids first). Report every such collision rather than hide it.
collisions = sorted(k for k, v in moves.items() if k in live_new and k != v)
out = {
    "$comment": "GENERATED by scripts/restructure-2026-10/build-moves.py. Old deep-link id -> the heading that holds its text after the October 2026 restructure.",
    "collisions": collisions,
    "moves": dict(sorted(moves.items())),
}
with open(os.path.join(ROOT, "lib", "anchors", "restructure-2026-10.json"), "w", encoding="utf8") as fh:
    json.dump(out, fh, indent=1)
    fh.write("\n")
print(f"build-moves: {sum(1 for r in MAPPING if r['oldRef'])} live headings and {len(old_redirects)} older redirects mapped; "
      f"{len(collisions)} old id(s) now name a different live heading")
for c in collisions:
    print(f"  collision: {c} (was -> {moves[c]}; now a live heading in its own right)")
